export function DashboardSidebar({ userName, userRole, userImage }: DashboardSidebarProps) {
  const pathname = usePathname();
  const [mobileOpen, setMobileOpen] = useState(false);

  const initial = (userName || "H").charAt(0).toUpperCase();

  const navContent = (
    <>
      <div className="p-5 border-b border-[#E8E6E1]">
        <Link href="/" className="block mb-5">
          <Logo />
        </Link>
        <div className="flex items-center gap-3">
          {userImage ? (
            <img src={userImage} alt={userName} className="w-9 h-9 rounded-full object-cover" referrerPolicy="no-referrer" />
          ) : (
            <div className="w-9 h-9 rounded-full bg-gradient-to-br from-[#FF4D00] to-[#E64500] flex items-center justify-center text-sm font-semibold text-white">
              {initial}
            </div>
          )}
          <div className="min-w-0">
            <p className="text-sm font-medium text-[#1A1A1A] truncate">{userName}</p>
            <p className="text-xs text-[#6B6B6B] capitalize">{userRole}</p>
          </div>
        </div>
      </div>

      <nav className="flex-1 p-3 space-y-1 overflow-y-auto">
        {hostLinks.map((link) => {
          const isActive = pathname === link.href ||
            (link.href !== "/dashboard/host" && pathname.startsWith(link.href));
          return (
            <Link
              key={link.href}
              href={link.href}
              onClick={() => setMobileOpen(false)}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                isActive
                  ? "bg-[#FFF1EB] text-[#FF4D00]"
                  : "text-[#6B6B6B] hover:bg-[#F0EFEC] hover:text-[#1A1A1A]"
              }`}
            >
              <span className={isActive ? "text-[#FF4D00]" : "text-[#999]"}>
                {link.icon}
              </span>
              {link.label}
            </Link>
          );
        })}

        {userRole === "admin" && (
          <>
            <div className="pt-3 pb-1 px-3">
              <p className="text-[10px] uppercase tracking-widest text-[#999] font-semibold">
                Admin
              </p>
            </div>
            {adminLinks.map((link) => {
              const isActive = pathname === link.href ||
                (link.href !== "/dashboard/admin" && pathname.startsWith(link.href));
              return (
                <Link
                  key={link.href}
                  href={link.href}
                  onClick={() => setMobileOpen(false)}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                    isActive
                      ? "bg-purple-50 text-purple-700"
                      : "text-[#6B6B6B] hover:bg-[#F0EFEC] hover:text-[#1A1A1A]"
                  }`}
                >
                  <span className={isActive ? "text-purple-600" : "text-[#999]"}>
                    {link.icon}
                  </span>
                  {link.label}
                </Link>
              );
            })}
          </>
        )}
      </nav>

      <div className="p-3 border-t border-[#E8E6E1] space-y-1">
        <Link
          href="/vehicles"
          className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm text-[#6B6B6B] hover:bg-[#F0EFEC] transition-colors"
        >
          <svg className="w-5 h-5 text-[#999]" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="m21 21-5.197-5.197m0 0A7.5 7.5 0 1 0 5.196 5.196a7.5 7.5 0 0 0 10.607 10.607Z" />
          </svg>
          Browse Cars
        </Link>
        <button
          onClick={() => signOut({ callbackUrl: "/login" })}
          className="flex items-center gap-3 w-full px-3 py-2.5 rounded-lg text-sm text-[#6B6B6B] hover:bg-[#F0EFEC] transition-colors cursor-pointer"
        >
          <svg className="w-5 h-5 text-[#999]" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0 0 13.5 3h-6a2.25 2.25 0 0 0-2.25 2.25v13.5A2.25 2.25 0 0 0 7.5 21h6a2.25 2.25 0 0 0 2.25-2.25V15m3 0 3-3m0 0-3-3m3 3H9" />
          </svg>
          Sign Out
        </button>
      </div>
    </>
  );

  return (
    <>
      {/* Mobile toggle */}
      <button
        onClick={() => setMobileOpen(true)}
        className="lg:hidden fixed top-4 left-4 z-50 p-2 bg-white rounded-lg shadow-md border border-[#E8E6E1] cursor-pointer"
      >
        <svg className="w-5 h-5 text-[#6B6B6B]" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2}>
          <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
        </svg>
      </button>

      {/* Mobile overlay */}
      {mobileOpen && (
        <div className="lg:hidden fixed inset-0 z-40">
          <div className="absolute inset-0 bg-black/30" onClick={() => setMobileOpen(false)} />
          <div className="absolute left-0 top-0 bottom-0 w-64 bg-white border-r border-[#E8E6E1] flex flex-col">
            <button
              onClick={() => setMobileOpen(false)}
              className="absolute top-4 right-4 p-1 text-[#999] hover:text-[#6B6B6B] cursor-pointer"
            >
              <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M6 18 18 6M6 6l12 12" />
              </svg>
            </button>
            {navContent}
          </div>
        </div>
      )}

      {/* Desktop sidebar */}
      <aside className="hidden lg:flex lg:flex-col lg:w-64 lg:border-r lg:border-[#E8E6E1] lg:bg-white lg:shrink-0">
        {navContent}
      </aside>
    </>
  );
}
